"""Independent deterministic demonstration. NOT the publisher's Kaggle dataset."""
import csv, io, json, math, random, zipfile
from datetime import date, timedelta
from pathlib import Path

def create_demo(path: Path) -> None:
    r=random.Random(1729); parts=[]; history=[]; orders=[]; incidents=[]
    start=date(2022,1,3)
    families=['Avionics','Engine systems','Structures','Actuation','Fasteners','Hydraulics']
    for i in range(60):
        pid=f'AP-{i+1:04d}'; family=families[i%6]
        parts.append(dict(part_id=pid,description=f'{family} component {i+1:02d}',part_family=family,
          criticality_class=['A','B','C'][i%3],unit_cost=round(r.uniform(80,4200),2),
          nominal_lead_time_days=[14,21,28,35,42,56][i%6],supplier_id=f'SUP-{i%12+1:02d}',
          supplier_risk=['Low','Medium','High'][i%3],repairable='true' if i%4==0 else 'false',shelf_life_days=''))
        for si in range(3):
            site=f'SITE-{si+1:02d}'; pattern=i%4; mu=r.uniform(3,16)*(1+si*.12)
            stock=round(mu*8); backlog=0; pipeline=[]; last=[]
            for t in range(156):
                dt=start+timedelta(weeks=t)
                stock+=sum(q for due,q in pipeline if due<=t);pipeline=[(d,q) for d,q in pipeline if d>t]
                served_old=min(stock,backlog);stock-=served_old;backlog-=served_old
                event=(r.random()<(.25 if pattern==2 else .18 if pattern==3 else 1))
                size=max(1,round(mu*(1+.18*math.sin(2*math.pi*t/52))*(1+.0012*t)*r.lognormvariate(-.08,.32 if pattern in (0,2) else .95)))
                demand=size if event else 0
                filled=min(stock,demand);stock-=filled;backlog+=demand-filled
                if t%4==0:
                    q=max(0,round(mu*(1 if pattern<2 else .3)*10)-stock-sum(q for _,q in pipeline)+backlog)
                    if q:
                        ld=max(7,parts[-1]['nominal_lead_time_days']+r.choice([-7,0,0,7,14])); arrival=t+math.ceil(ld/7)
                        pipeline.append((arrival,q)); oid=f'PO-{len(orders)+1:06d}'
                        orders.append(dict(po_id=oid,part_id=pid,site_id=site,supplier_id=parts[-1]['supplier_id'],order_date=str(dt),
                          promised_receipt_date=str(dt+timedelta(days=parts[-1]['nominal_lead_time_days'])),
                          actual_receipt_date=str(dt+timedelta(days=ld)),quantity=q,received_quantity=q))
                        if r.random()<.025: incidents.append(dict(incident_id=f'QI-{len(incidents)+1:04d}',po_id=oid,part_id=pid,severity=r.choice(['Minor','Major']),scrap_quantity=r.randint(1,3)))
                base=sum(last[-8:])/len(last[-8:]) if last else mu
                history.append(dict(site_id=site,part_id=pid,week=str(dt),actual_consumption=demand,
                  on_hand_inventory=stock,backorders=backlog,blocked_stock=min(stock,r.randint(0,2)) if t%19==0 else 0,
                  baseline_forecast=round(base,3),adjusted_forecast=round(base*1.08,3),maintenance_type='Unplanned' if pattern>=2 and demand else 'Planned'))
                last.append(demand)
    path.parent.mkdir(parents=True,exist_ok=True)
    with zipfile.ZipFile(path,'w',zipfile.ZIP_DEFLATED) as z:
        for name,rows in [('parts_master.csv',parts),('supply_chain_history.csv',history),('purchase_orders.csv',orders),('quality_incidents.csv',incidents)]:
            s=io.StringIO(newline='');w=csv.DictWriter(s,fieldnames=list(rows[0]));w.writeheader();w.writerows(rows);z.writestr(name,s.getvalue())
        z.writestr('DEMONSTRATION_NOTICE.txt','Independently generated test data, seed 1729. NOT the Kaggle aerospace dataset. Do not report these results as Kaggle findings. Generated by app/demo.py. MIT licensed with this application.')
        z.writestr('demo_metadata.json',json.dumps(dict(seed=1729,parts=len(parts),history_rows=len(history),purchase_orders=len(orders),quality_incidents=len(incidents)),indent=2))
